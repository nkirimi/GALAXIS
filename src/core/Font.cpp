const Glyph* findGlyph(char ch) {
    static std::array<const Glyph*, 128> table = [] {
        std::array<const Glyph*, 128> t{};
        for (const Glyph& g : kGlyphs) t[static_cast<unsigned char>(g.ch)] = &g;
        return t;
    }();
    const unsigned char u = static_cast<unsigned char>(ch);
    if (u >= 128) return nullptr;
    if (table[u]) return table[u];
    const unsigned char up = static_cast<unsigned char>(std::toupper(u));
    return table[up];
}

