void drawText(Canvas& c, int x, int y, const std::string& text, Color col, int scale, double alpha) {
    int cx = x, cy = y;
    for (char ch : text) {
        if (ch == '\n') {
            cx = x;
            cy += kLineHeight * scale;
            continue;
        }
        if (ch != ' ') {
            const Glyph* g = findGlyph(ch);
            for (int row = 0; row < 9; ++row) {
                if (g && !g->rows[row]) break;  // no more rows defined
                if (!g && row > 6) break;
                for (int colIdx = 0; colIdx < 5; ++colIdx) {
                    const bool on = g ? g->rows[row][colIdx] == '1'
                                      : (row == 0 || row == 6 || colIdx == 0 || colIdx == 4);  // unknown: box
                    if (!on) continue;
                    for (int sy = 0; sy < scale; ++sy)
                        for (int sx = 0; sx < scale; ++sx)
                            c.blendPixel(cx + colIdx * scale + sx, cy + row * scale + sy, col, alpha);
                }
            }
        }
        cx += 6 * scale;
    }
}

std::vector<std::string> wrapText(const std::string& text, int maxWidth, int scale) {
    std::vector<std::string> lines;
    std::string line, word;
    auto flushWord = [&] {
        if (word.empty()) return;
        const std::string candidate = line.empty() ? word : line + " " + word;
        if (!line.empty() && textWidth(candidate, scale) > maxWidth) {
            lines.push_back(line);
            line = word;
        } else {
            line = candidate;
        }
        word.clear();
    };
    for (char ch : text) {
        if (ch == ' ' || ch == '\n') {
            flushWord();
            if (ch == '\n') {
                lines.push_back(line);
                line.clear();
            }
        } else {
            word += ch;
        }
    }
    flushWord();
    if (!line.empty()) lines.push_back(line);
    return lines;
}

int textWidth(const std::string& text, int scale) {
    int longest = 0, current = 0;
    for (char ch : text) {
        if (ch == '\n') {
            longest = std::max(longest, current);
            current = 0;
        } else {
            ++current;
        }
    }
    longest = std::max(longest, current);
    return longest == 0 ? 0 : longest * 6 * scale - scale;
}

